// Current language: ?lang=fr|en in the address wins, then the visitor's last choice.
window.LANG = (function () {
  const q = new URLSearchParams(location.search).get("lang");
  let l = q === "fr" || q === "en" ? q : null;
  try {
    if (l) localStorage.setItem("lang", l);
    else l = localStorage.getItem("lang");
  } catch (e) {}
  return l === "fr" ? "fr" : "en";
})();

// Projects in the current language (same shape as PROJECTS)
if (window.LANG === "fr" && window.PROJECTS) {
  window.PROJECTS = window.PROJECTS.map((p) => {
    const f = window.FR.projects[p.slug];
    return f ? { ...p, title: f.title || p.title, facts: f.facts || p.facts, intent: f.intent !== undefined ? f.intent : p.intent } : p;
  });
}
